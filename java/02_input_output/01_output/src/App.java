public class App {
    public static void main(String[] args) throws Exception {
        // Stampo un numero andando a capo
        System.out.println(104);
        // Stampo una stringa andando a capo
        System.out.println("Va a capo");
        // Stampo una stringa senza andare a capo
        System.out.print("Non va a capo ");
        System.out.println("e continua");
        // Concatenazione di stringhe
        System.out.println("Concatenazione" + " di " + "stringhe");
        // Stampare un messaggio di errore
        System.err.println("Messaggio di errore");
    }
}