public class App {
    public static void main(String[] args) throws Exception {
        // Operatori di confronto
        int a = 5;
        int b = 10;
        System.out.println(a == b); // false
        System.out.println(a != b); // true
        System.out.println(a > b); // false
        System.out.println(a < b); // true
        System.out.println(a >= b); // false
        System.out.println(a <= b); // true
    }
}
